CREATE TABLE IF NOT EXISTS moderation_task (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    task_id VARCHAR(64) NOT NULL,
    request_id VARCHAR(64) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    content_type VARCHAR(16) NOT NULL,
    user_id VARCHAR(128) NULL,
    content TEXT NULL,
    image_url VARCHAR(1024) NULL,
    image_data LONGTEXT NULL,
    status VARCHAR(16) NOT NULL,
    decision VARCHAR(16) NULL,
    violation BOOLEAN NULL,
    confidence DOUBLE NULL,
    reason TEXT NULL,
    error_message VARCHAR(512) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    completed_at DATETIME NULL,
    UNIQUE KEY uk_moderation_task_task_id (task_id),
    INDEX idx_moderation_task_request_hash_status (request_hash, status),
    INDEX idx_moderation_task_status (status),
    INDEX idx_moderation_task_created_at (created_at)
);
